// One-off generator: extracts real brand-mark path data + official hex
// color from the simple-icons package (devDependency only, never shipped to
// the client) into a small static TS file the Ecosystem marquee imports
// directly. Re-run if the marquee's platform list changes.
import { readFileSync, writeFileSync } from "node:fs";

// Only the platforms without a real supplied logo asset still come from
// here — everything else in the marquee now uses an actual brand PNG.
const ICONS = {
  youtube: "youtube",
  facebook: "facebook",
};

const si = await import("simple-icons");

const entries = Object.entries(ICONS).map(([key, slug]) => {
  const svg = readFileSync(
    new URL(`../node_modules/simple-icons/icons/${slug}.svg`, import.meta.url),
    "utf-8"
  );
  const match = svg.match(/<path d="([^"]+)"/);
  if (!match) throw new Error(`No path found for ${slug}`);

  const exportKey = `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`;
  const hex = si[exportKey]?.hex;
  if (!hex) throw new Error(`No hex found for ${slug}`);

  return [key, { path: match[1], hex: `#${hex}` }];
});

const out = `// Generated by scripts/generate-marquee-logos.mjs — real brand marks +
// official colors sourced from the simple-icons package (CC0/MIT), baked in
// at build time so the package itself never ships to the client. Re-run the
// script if the marquee's platform list changes.
export const MARQUEE_LOGOS: Record<string, { path: string; hex: string }> = {
${entries.map(([key, v]) => `  ${key}: { path: "${v.path}", hex: "${v.hex}" },`).join("\n")}
};
`;

writeFileSync(new URL("../src/components/icons/marqueeLogos.ts", import.meta.url), out);
console.log(`Generated ${entries.length} marquee logo entries.`);
